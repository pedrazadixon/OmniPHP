//! Apache configuration: one generated `httpd.conf` plus one vhost file per
//! site. PHP runs through mod_fcgid, configured *inside each vhost*, which is
//! what lets every site have its own PHP version and php.ini.

use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::{Context, Result, bail};

use super::config::ApacheConfig;
use super::paths::{Paths, slash};
use super::php::MailCatcher;
use super::proc::quiet_command;
use super::runtimes::{ApacheRuntime, PhpRuntime};
use super::sites::Site;
use super::ssl::SiteCertificate;

/// Name of the pseudo-site behind `http://localhost/` (serves the sites folder).
pub const DEFAULT_SITE: &str = "_default";

/// Stock modules loaded when the Apache build ships them.
const MODULES: [&str; 22] = [
    "access_compat", "alias", "auth_basic", "authn_core", "authn_file", "authz_core",
    "authz_groupfile", "authz_host", "authz_user", "autoindex", "deflate", "dir", "env",
    "expires", "filter", "headers", "log_config", "mime", "negotiation", "rewrite",
    "setenvif", "version",
];

/// Modules HTTPS needs on top of [`MODULES`].
const SSL_MODULES: [&str; 2] = ["ssl", "socache_shmcb"];

/// Whether this Apache build can serve HTTPS at all.
pub fn ssl_available(apache: &ApacheRuntime) -> bool {
    SSL_MODULES
        .into_iter()
        .all(|module| apache.dir.join("modules").join(format!("mod_{module}.so")).is_file())
}

/// `https_port` is `Some` when HTTPS is enabled and available.
pub fn render_httpd_conf(
    apache: &ApacheRuntime,
    config: &ApacheConfig,
    https_port: Option<u16>,
    paths: &Paths,
) -> String {
    let mut conf = String::new();
    let logs = slash(&paths.logs());
    let etc = slash(&paths.apache_etc());
    let tmp = slash(&paths.tmp());
    let _ = write!(
        conf,
        "# Generated by OmniPHP. Do not edit: this file is overwritten.\n\
         # Put your own directives in {etc}/custom/*.conf instead.\n\n\
         Define SRVROOT \"{root}\"\n\
         ServerRoot \"${{SRVROOT}}\"\n\
         Listen {listen}:{port}\n",
        root = slash(&apache.dir),
        listen = config.listen,
        port = config.http_port,
    );
    if let Some(https_port) = https_port {
        let _ = writeln!(conf, "Listen {}:{https_port} https", config.listen);
    }
    let _ = write!(
        conf,
        "ServerName localhost:{port}\n\
         PidFile \"{tmp}/httpd.pid\"\n\
         ErrorLog \"{logs}/apache-error.log\"\n\
         LogLevel warn\n\n",
        port = config.http_port,
    );

    let ssl_modules = if https_port.is_some() { &SSL_MODULES[..] } else { &[] };
    for module in MODULES.iter().chain(ssl_modules) {
        if apache.dir.join("modules").join(format!("mod_{module}.so")).is_file() {
            let _ = writeln!(conf, "LoadModule {module}_module modules/mod_{module}.so");
        }
    }
    let _ = writeln!(conf, "LoadModule fcgid_module \"{}\"", slash(&paths.fcgid_module()));
    if https_port.is_some() {
        let _ = write!(
            conf,
            "\nSSLProtocol -all +TLSv1.2 +TLSv1.3\n\
             SSLSessionCache \"shmcb:{tmp}/ssl_scache(512000)\"\n\
             SSLSessionCacheTimeout 300\n",
        );
    }

    let _ = write!(
        conf,
        "\nTypesConfig conf/mime.types\n\
         DirectoryIndex index.php index.html index.htm\n\
         AcceptFilter http none\n\
         EnableSendfile Off\n\
         EnableMMAP Off\n\n\
         <Directory />\n    AllowOverride None\n    Require all denied\n</Directory>\n\
         <Files \".ht*\">\n    Require all denied\n</Files>\n\n\
         <IfModule log_config_module>\n\
         \x20   LogFormat \"%h %l %u %t \\\"%r\\\" %>s %b\" common\n\
         \x20   CustomLog \"{logs}/apache-access.log\" common\n\
         </IfModule>\n\n\
         FcgidIOTimeout 600\n\
         FcgidConnectTimeout 16\n\
         FcgidMaxRequestsPerProcess 0\n\
         FcgidMaxProcesses 50\n\
         FcgidMaxRequestLen 1073741824\n\n\
         IncludeOptional \"{etc}/sites/*.conf\"\n\
         IncludeOptional \"{etc}/custom/*.conf\"\n",
    );
    conf
}

/// The vhosts of one site: always HTTP, plus HTTPS when `tls` gives a port and
/// certificate. `php` is the runtime the site resolved to, if any.
pub fn render_vhost(
    site: &Site,
    php: Option<&PhpRuntime>,
    http_port: u16,
    tls: Option<(u16, &SiteCertificate)>,
    paths: &Paths,
) -> String {
    let body = render_vhost_body(site, php, paths);
    let mut conf = format!(
        "# Generated by OmniPHP for \"{}\". Do not edit: this file is overwritten.\n\
         <VirtualHost *:{http_port}>\n{body}</VirtualHost>\n",
        site.name
    );
    if let Some((https_port, certificate)) = tls {
        let _ = write!(
            conf,
            "\n<VirtualHost *:{https_port}>\n{body}\
             \x20   SSLEngine on\n\
             \x20   SSLCertificateFile \"{cert}\"\n\
             \x20   SSLCertificateKeyFile \"{key}\"\n\
             </VirtualHost>\n",
            cert = slash(&certificate.cert),
            key = slash(&certificate.key),
        );
    }
    conf
}

/// Everything inside `<VirtualHost>` that HTTP and HTTPS share.
fn render_vhost_body(site: &Site, php: Option<&PhpRuntime>, paths: &Paths) -> String {
    let root = slash(&site.document_root);
    let mut conf = String::new();
    let _ = writeln!(conf, "    ServerName {}", site.hostname);
    if site.name != DEFAULT_SITE {
        let mut aliases = vec![format!("*.{}", site.hostname)];
        aliases.extend(site.aliases.iter().cloned());
        let _ = writeln!(conf, "    ServerAlias {}", aliases.join(" "));
    }
    let _ = writeln!(conf, "    DocumentRoot \"{root}\"");

    if let Some(php) = php {
        let windows = std::env::var("SystemRoot").unwrap_or_else(|_| r"C:\Windows".into());
        let windows = windows.replace('\\', "/");
        let drive = std::env::var("SystemDrive").unwrap_or_else(|_| "C:".into());
        let tmp = slash(&paths.tmp());
        // php-cgi starts with only this environment, so the Windows basics it
        // needs to load DLLs and open sockets are passed explicitly.
        let _ = write!(
            conf,
            "    FcgidInitialEnv PHPRC \"{phprc}\"\n\
             \x20   FcgidInitialEnv PHP_FCGI_MAX_REQUESTS 0\n\
             \x20   FcgidInitialEnv SystemRoot \"{windows}\"\n\
             \x20   FcgidInitialEnv SystemDrive \"{drive}\"\n\
             \x20   FcgidInitialEnv windir \"{windows}\"\n\
             \x20   FcgidInitialEnv TEMP \"{tmp}\"\n\
             \x20   FcgidInitialEnv TMP \"{tmp}\"\n\
             \x20   FcgidInitialEnv PATH \"{php_dir};{windows}/system32;{windows}\"\n",
            phprc = slash(&paths.php_site_dir(&site.name)),
            php_dir = slash(&php.dir),
        );
    }

    let options = if site.name == DEFAULT_SITE {
        "+ExecCGI +FollowSymLinks +Indexes"
    } else {
        "+ExecCGI +FollowSymLinks"
    };
    let _ = write!(
        conf,
        "    <Directory \"{root}\">\n\
         \x20       AllowOverride All\n\
         \x20       Require all granted\n\
         \x20       Options {options}\n",
    );
    if let Some(php) = php {
        let _ = write!(
            conf,
            "        CGIPassAuth On\n\
             \x20       <FilesMatch \"\\.php$\">\n\
             \x20           SetHandler fcgid-script\n\
             \x20       </FilesMatch>\n\
             \x20       FcgidWrapper \"{cgi}\" .php\n",
            cgi = slash(&php.cgi()),
        );
    }
    conf.push_str("    </Directory>\n");

    if let (true, Some(php)) = (site.name == DEFAULT_SITE, php) {
        // Adminer, the database tool, lives at http://localhost/adminer and
        // answers this PC only: it logs in to MySQL without a password.
        let adminer = slash(&super::tools::adminer_dir(paths));
        let _ = write!(
            conf,
            "    Alias /adminer \"{adminer}\"\n\
             \x20   <Directory \"{adminer}\">\n\
             \x20       AllowOverride None\n\
             \x20       Require local\n\
             \x20       Options +ExecCGI\n\
             \x20       <FilesMatch \"\\.php$\">\n\
             \x20           SetHandler fcgid-script\n\
             \x20       </FilesMatch>\n\
             \x20       FcgidWrapper \"{cgi}\" .php\n\
             \x20   </Directory>\n",
            cgi = slash(&php.cgi()),
        );
    }
    conf
}

/// Writes `httpd.conf`, every vhost and every site's php.ini, replacing what a
/// previous run generated. `certificates` maps site names to their
/// certificate; sites without one are served over HTTP only.
pub fn write_all(
    apache: &ApacheRuntime,
    config: &ApacheConfig,
    https_port: Option<u16>,
    certificates: &HashMap<String, SiteCertificate>,
    mail: Option<&MailCatcher>,
    default_site: &Site,
    sites: &[Site],
    phps: &[PhpRuntime],
    paths: &Paths,
) -> Result<()> {
    paths.ensure_dirs()?;
    let find_php = |site: &Site| {
        site.php.as_ref().and_then(|id| phps.iter().find(|php| &php.id == id))
    };

    write(&paths.apache_conf(), &render_httpd_conf(apache, config, https_port, paths))?;

    let sites_dir = paths.apache_sites();
    remove_children(&sites_dir, |path| path.extension().is_some_and(|ext| ext == "conf"))?;
    // "00-" sorts first, and Apache treats the first vhost as the fallback.
    let all = std::iter::once((String::from("00-default.conf"), default_site))
        .chain(sites.iter().map(|site| (format!("site-{}.conf", site.name), site)));
    let mut live_ini_dirs = Vec::new();
    for (file, site) in all {
        let php = find_php(site);
        let tls = https_port.zip(certificates.get(&site.name));
        write(&sites_dir.join(file), &render_vhost(site, php, config.http_port, tls, paths))?;
        if let Some(php) = php {
            super::php::write_site_ini(site, php, mail, paths)?;
            live_ini_dirs.push(paths.php_site_dir(&site.name));
        }
    }

    // Drop php.ini folders of sites that no longer exist.
    if let Some(ini_root) = paths.php_site_dir("x").parent() {
        remove_children(ini_root, |path| path.is_dir() && !live_ini_dirs.contains(&path.to_path_buf()))?;
    }
    Ok(())
}

/// Runs `httpd -t` against the generated configuration.
pub fn validate(apache: &ApacheRuntime, paths: &Paths) -> Result<()> {
    if !paths.fcgid_module().is_file() {
        bail!(
            "mod_fcgid is missing: expected {} (it must match the Apache build; fetch-runtimes.bat downloads it)",
            paths.fcgid_module().display()
        );
    }
    let output = quiet_command(apache.httpd())
        .arg("-t")
        .arg("-f")
        .arg(paths.apache_conf())
        .output()
        .with_context(|| format!("cannot run {}", apache.httpd().display()))?;
    if !output.status.success() {
        bail!(
            "Apache rejected the configuration:\n{}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(())
}

fn write(path: &Path, text: &str) -> Result<()> {
    std::fs::write(path, text).with_context(|| format!("cannot write {}", path.display()))
}

fn remove_children(dir: &Path, should_remove: impl Fn(&Path) -> bool) -> Result<()> {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return Ok(());
    };
    for path in entries.flatten().map(|entry| entry.path()) {
        if should_remove(&path) {
            let result = if path.is_dir() {
                std::fs::remove_dir_all(&path)
            } else {
                std::fs::remove_file(&path)
            };
            result.with_context(|| format!("cannot remove {}", path.display()))?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn paths() -> Paths {
        Paths::new(r"D:\OmniPHP")
    }

    fn php() -> PhpRuntime {
        PhpRuntime {
            id: "php-8.3".into(),
            version: "8.3.37".into(),
            thread_safe: true,
            dir: PathBuf::from(r"D:\OmniPHP\bin\php\php-8.3"),
            extensions: vec![],
        }
    }

    fn site() -> Site {
        Site {
            name: "shop".into(),
            dir: PathBuf::from(r"D:\OmniPHP\www\shop"),
            hostname: "shop.test".into(),
            aliases: vec!["store.test".into()],
            document_root: PathBuf::from(r"D:\OmniPHP\www\shop\public"),
            php: Some("php-8.3".into()),
            extensions: vec![],
            ini: Default::default(),
        }
    }

    #[test]
    fn https_vhost_repeats_the_site_with_its_certificate() {
        let certificate = SiteCertificate {
            cert: PathBuf::from(r"D:\OmniPHP\etc\ssl\sites\shop.test.crt"),
            key: PathBuf::from(r"D:\OmniPHP\etc\ssl\sites\shop.test.key"),
        };
        let conf = render_vhost(&site(), Some(&php()), 80, Some((443, &certificate)), &paths());
        assert!(conf.contains("<VirtualHost *:80>"));
        assert!(conf.contains("<VirtualHost *:443>"));
        assert_eq!(conf.matches("ServerName shop.test").count(), 2);
        assert_eq!(conf.matches("FcgidWrapper").count(), 2, "PHP must work on both");
        assert_eq!(conf.matches("SSLEngine on").count(), 1);
        assert!(conf.contains("SSLCertificateFile \"D:/OmniPHP/etc/ssl/sites/shop.test.crt\""));
        assert!(conf.contains("SSLCertificateKeyFile \"D:/OmniPHP/etc/ssl/sites/shop.test.key\""));
    }

    #[test]
    fn vhost_binds_the_site_to_its_own_php() {
        let conf = render_vhost(&site(), Some(&php()), 80, None, &paths());
        assert!(!conf.contains("SSLEngine"));
        assert!(conf.contains("<VirtualHost *:80>"));
        assert!(conf.contains("ServerName shop.test"));
        assert!(conf.contains("ServerAlias *.shop.test store.test"));
        assert!(conf.contains("DocumentRoot \"D:/OmniPHP/www/shop/public\""));
        assert!(conf.contains("FcgidInitialEnv PHPRC \"D:/OmniPHP/etc/php/sites/shop\""));
        assert!(conf.contains("FcgidWrapper \"D:/OmniPHP/bin/php/php-8.3/php-cgi.exe\" .php"));
        assert!(conf.contains("SetHandler fcgid-script"));
        assert!(!conf.contains("+Indexes"));
    }

    #[test]
    fn vhost_without_php_serves_static_files_only() {
        let conf = render_vhost(&site(), None, 8080, None, &paths());
        assert!(conf.contains("<VirtualHost *:8080>"));
        assert!(!conf.contains("Fcgid"));
        assert!(conf.contains("Require all granted"));
    }

    #[test]
    fn httpd_conf_uses_configured_address_and_includes_sites() {
        let apache = ApacheRuntime {
            id: "httpd-2.4.71".into(),
            version: "2.4.71".into(),
            dir: PathBuf::from(r"D:\OmniPHP\bin\apache\httpd-2.4.71"),
        };
        let config = ApacheConfig { http_port: 8080, ..Default::default() };
        let with_ssl = render_httpd_conf(&apache, &config, Some(8443), &paths());
        assert!(with_ssl.contains("Listen 127.0.0.1:8443 https"));
        assert!(with_ssl.contains("SSLSessionCache \"shmcb:D:/OmniPHP/tmp/ssl_scache(512000)\""));

        let conf = render_httpd_conf(&apache, &config, None, &paths());
        assert!(!conf.contains("SSL"));
        assert!(conf.contains("Listen 127.0.0.1:8080"));
        assert!(conf.contains("ServerRoot \"${SRVROOT}\""));
        assert!(conf.contains("LoadModule fcgid_module \"D:/OmniPHP/bin/mod_fcgid/mod_fcgid.so\""));
        assert!(conf.contains("IncludeOptional \"D:/OmniPHP/etc/apache/sites/*.conf\""));
        assert!(conf.contains("LogFormat \"%h %l %u %t \\\"%r\\\" %>s %b\" common"));
    }
}
