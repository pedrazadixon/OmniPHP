//! MySQL configuration and first-run initialisation.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

use super::config::MysqlConfig;
use super::paths::{Paths, slash};
use super::proc::quiet_command;
use super::runtimes::ToolRuntime;

/// MySQL only accepts connections from this PC: root starts without a password.
pub const LISTEN: &str = "127.0.0.1";

pub fn error_log(paths: &Paths) -> PathBuf {
    paths.logs().join("mysql-error.log")
}

/// Data lives per release series (`data\mysql-8.4`), so patch upgrades of
/// MySQL keep their databases while a new series starts clean.
pub fn data_dir(runtime: &ToolRuntime, paths: &Paths) -> PathBuf {
    let series: Vec<&str> = runtime.version.split('.').take(2).collect();
    paths.data().join(format!("mysql-{}", series.join(".")))
}

pub fn render_config(runtime: &ToolRuntime, config: &MysqlConfig, paths: &Paths) -> String {
    format!(
        "# Generated by OmniPHP. Do not edit: this file is overwritten.\n\
         [mysqld]\n\
         basedir=\"{base}\"\n\
         datadir=\"{data}\"\n\
         port={port}\n\
         bind-address={LISTEN}\n\
         # The X Protocol listener (33060) is not needed for PHP development.\n\
         mysqlx=0\n\
         log-error=\"{log}\"\n\
         max_allowed_packet=512M\n\
         \n\
         [client]\n\
         port={port}\n",
        base = slash(&runtime.dir),
        data = slash(&data_dir(runtime, paths)),
        port = config.port,
        log = slash(&error_log(paths)),
    )
}

pub fn write_config(runtime: &ToolRuntime, config: &MysqlConfig, paths: &Paths) -> Result<PathBuf> {
    let dir = paths.etc().join("mysql");
    std::fs::create_dir_all(&dir).with_context(|| format!("cannot create {}", dir.display()))?;
    std::fs::create_dir_all(paths.logs())?;
    let file = dir.join("my.ini");
    std::fs::write(&file, render_config(runtime, config, paths))
        .with_context(|| format!("cannot write {}", file.display()))?;
    Ok(file)
}

/// Creates the system tables the first time this MySQL series is used.
pub fn initialize_if_needed(runtime: &ToolRuntime, my_ini: &Path, paths: &Paths) -> Result<()> {
    let data = data_dir(runtime, paths);
    // The `mysql` schema folder exists in every initialised data directory.
    if data.join("mysql").is_dir() {
        return Ok(());
    }
    let has_files = std::fs::read_dir(&data).is_ok_and(|mut entries| entries.next().is_some());
    if has_files {
        bail!(
            "{} contains files but is not a MySQL data directory. Move them away so MySQL \
             can create its databases there.",
            data.display()
        );
    }
    if let Some(parent) = data.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let output = quiet_command(&runtime.exe)
        .arg(format!("--defaults-file={}", my_ini.display()))
        .arg("--initialize-insecure")
        .output()
        .with_context(|| format!("cannot run {}", runtime.exe.display()))?;
    if !output.status.success() || !data.join("mysql").is_dir() {
        bail!(
            "MySQL could not create its data directory. See {} for details.",
            error_log(paths).display()
        );
    }
    Ok(())
}

/// Creates an empty utf8mb4 database (root, no password) if it is not there yet.
pub fn create_database(runtime: &ToolRuntime, port: u16, name: &str) -> Result<()> {
    if name.is_empty() || !name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') {
        bail!("\"{name}\" cannot be used as a database name.");
    }
    let client = runtime.dir.join("bin").join("mysql.exe");
    let output = quiet_command(&client)
        .args(["--protocol=TCP", "-h", LISTEN, "-u", "root"])
        .arg(format!("--port={port}"))
        .arg("-e")
        .arg(format!("CREATE DATABASE IF NOT EXISTS `{name}` CHARACTER SET utf8mb4"))
        .output()
        .with_context(|| format!("cannot run {}", client.display()))?;
    if !output.status.success() {
        bail!(
            "MySQL could not create the database {name}: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn runtime(version: &str) -> ToolRuntime {
        let dir = PathBuf::from(r"D:\OmniPHP\bin\mysql\mysql-x");
        ToolRuntime {
            id: "mysql-x".into(),
            version: version.into(),
            exe: dir.join("bin").join("mysqld.exe"),
            dir,
        }
    }

    #[test]
    fn data_directory_is_shared_within_a_release_series() {
        let paths = Paths::new(r"D:\OmniPHP");
        assert_eq!(slash(&data_dir(&runtime("8.4.3"), &paths)), "D:/OmniPHP/data/mysql-8.4");
        assert_eq!(data_dir(&runtime("8.4.9"), &paths), data_dir(&runtime("8.4.3"), &paths));
        assert_ne!(data_dir(&runtime("9.1.0"), &paths), data_dir(&runtime("8.4.3"), &paths));
    }

    #[test]
    fn config_is_local_only_and_uses_the_chosen_port() {
        let config = MysqlConfig { port: 3307, ..Default::default() };
        let ini = render_config(&runtime("8.4.3"), &config, &Paths::new(r"D:\OmniPHP"));
        assert!(ini.contains("bind-address=127.0.0.1"));
        assert_eq!(ini.matches("port=3307").count(), 2);
        assert!(ini.contains("datadir=\"D:/OmniPHP/data/mysql-8.4\""));
        assert!(ini.contains("log-error=\"D:/OmniPHP/logs/mysql-error.log\""));
    }
}
